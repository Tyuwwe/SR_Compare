// Rasterize the glyph table into an R8 atlas (kFontAtlasW x kFontAtlasH).
inline void buildFontAtlas(uint8_t* out) {
    std::memset(out, 0, kFontAtlasW * kFontAtlasH);
    for (uint32_t g = 0; g < kFontGlyphCount; ++g) {
        const uint32_t cellX = (g % kFontAtlasCols) * kFontCellW;
        const uint32_t cellY = (g / kFontAtlasCols) * kFontCellH;
        for (uint32_t row = 0; row < kFontGlyphH; ++row) {
            const char* bits = font5x7::kGlyphs[g][row];
            for (uint32_t col = 0; col < kFontGlyphW; ++col) {
                if (bits[col] == '#') out[(cellY + row) * kFontAtlasW + cellX + col] = 255;
            }
        }
    }
}

